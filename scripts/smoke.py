#!/usr/bin/env python3
"""Regenerate docs/examples/ by running `contribpolicy show` against real repositories.

Read-only: it only performs GET requests against the GitHub API and
raw.githubusercontent.com. Set GITHUB_TOKEN (or be logged in with `gh`) to
avoid the 60 requests/hour unauthenticated limit.

    python scripts/smoke.py            # all repositories
    python scripts/smoke.py fluxcd/flux2
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

from contribpolicy import render
from contribpolicy.discover import GitHubReader, discover
from contribpolicy.extract import extract
from contribpolicy.github import GitHub, resolve_token
from contribpolicy.registry import load_registry

REPOS = [
    "kubernetes-sigs/kueue",
    "thanos-io/thanos",
    "jaegertracing/jaeger",
    "cortexproject/cortex",
    "radius-project/radius",
    "microsoft/agent-framework",
    "grafana/mimir",
    "fluxcd/flux2",
    "tektoncd/pipeline",
    "tj/commander.js",  # no AI policy
]

# Findings from reading each repository's sources next to the output (2026-10-12).
REVIEW_NOTES = [
    "`kubernetes-sigs/kueue`: the AI rules come from the repository's AGENTS.md and from the org registry "
    "(kubernetes.dev AI Guidance); both agree. CLA comes from CONTRIBUTING.md.",
    '`thanos-io/thanos`: matches CONTRIBUTING.md "AI Guidance" line by line.',
    "`jaegertracing/jaeger`: the AI-usage checkbox comes from the org-wide PR template in `jaegertracing/.github`. "
    "`human_only: review-replies` is **stricter than the source**: AI_POLICY.md lets AI help you word a reply you "
    "read and stand behind, and forbids letting an agent answer review feedback autonomously.",
    '`cortexproject/cortex` and `microsoft/agent-framework`: disclosure is conditional ("significant" / '
    '"material" AI use) and is reported as `required: true`; the condition is in the evidence quote.',
    "`radius-project/radius`: `restricted` with the label groups. The other conditions (issue not assigned to "
    "someone else, no open PR, re-check right before opening) are only in the evidence. No disclosure rule exists.",
    "`grafana/mimir`: no AI policy (`unspecified`); the signed-and-verified commit rule is detected. The doc notes "
    "that it also applies to commits authored with AI tools.",
    "`fluxcd/flux2`: Flux asks for disclosure in the PR description **and** an `Assisted-by` trailer; `where` lists "
    "both channels but cannot express that both are required.",
    "`tektoncd/pipeline`: the repository's own docs do not mention AI; every AI rule comes from the org registry "
    'entry. The trailer is "preferred" (reported `allowed`) with the PR description as the alternative.',
    "`tj/commander.js`: no AI policy; nothing is reported.",
]

OUT = Path(__file__).resolve().parent.parent / "docs" / "examples"


def main(argv: list[str]) -> int:
    repos = argv or REPOS
    gh = GitHub(token=resolve_token())
    registry = load_registry()
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for repo in repos:
        info = gh.repo_info(repo)
        if info is None:
            print(f"skip {repo}: not found", file=sys.stderr)
            continue
        slug = info["full_name"]
        found = discover(GitHubReader(gh, slug), slug, org_reader=lambda r: GitHubReader(gh, r), registry=registry)
        p = extract(slug, found.docs, found.sources)
        p.warnings = found.warnings + p.warnings
        stem = slug.replace("/", "__")
        (OUT / f"{stem}.json").write_text(render.render(p, "json"), encoding="utf-8")
        (OUT / f"{stem}.txt").write_text(render.render_table(p, width=110), encoding="utf-8")
        (OUT / f"{stem}.agents.md").write_text(render.render_agents_md(p), encoding="utf-8")
        d = p.to_dict()
        rows.append(
            "| `{}` | {} | {} | {} / {} | {} |".format(
                slug,
                d["ai_use"],
                ", ".join(d["disclosure"]["where"]) or ("required" if d["disclosure"]["required"] else "-"),
                d["trailers"]["assisted_by"],
                d["trailers"]["co_authored_by_ai"],
                ", ".join(d["human_only"]) or "-",
            )
        )
        print(f"{slug}: {json.dumps({k: d[k] for k in ('ai_use', 'trailers', 'human_only')})}")
    if not argv:
        index = [
            "# Example outputs",
            "",
            f"Generated by `python scripts/smoke.py` (read-only GitHub requests) on {date.today().isoformat()}. "
            "Each repository has a",
            "`.json` (the shared schema), a `.txt` (the default table) and an `.agents.md` (the `agents-md` block).",
            "These are snapshots: the upstream documents change, so re-run the script before relying on them.",
            "",
            "| Repository | ai_use | disclosure | Assisted-by / AI Co-authored-by | human-only |",
            "| --- | --- | --- | --- | --- |",
            *rows,
            "",
            "## Review notes (2026-10-12)",
            "",
            "Each output was compared with the source documents by hand. Known gaps:",
            "",
            *[f"- {n}" for n in REVIEW_NOTES],
            "",
        ]
        (OUT / "README.md").write_text("\n".join(index), encoding="utf-8")
    print(f"{gh.requests} HTTP requests", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
