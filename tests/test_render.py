def test_agents_md_kubernetes_style(k8s):
    out = render.render_agents_md(k8s)
    assert out.startswith("<!-- generated by contribpolicy")
    assert "Disclose AI assistance in the PR description." in out
    assert 'Example: "Parts of this PR were drafted with help from an AI assistant."' in out
    assert "Do NOT add `Assisted-by`" in out
    assert "Do NOT list an AI tool as co-author" in out
    assert "A human must write replies to review comments" in out
    assert "A human must write commit messages" in out
    assert "#L18" in out
    assert "Run the tests locally" in out
    assert "[org registry] https://k8s.dev/ai" in out


def test_agents_md_restricted_and_required_trailer():
    r = render.render_agents_md(policy_for("radius_style", repo="acme/radius"))
    assert "restricted" in r and "`triaged` AND (`help wanted` OR `good first issue`)" in r
    assert "cryptographically signed" in r and "screenshots" in r and "git commit -s" in r
    f = render.render_agents_md(policy_for("flux_style"))
    assert "Add an `Assisted-by: <agent>/<model>` trailer to every commit." in f
    t = render.render_agents_md(policy_for("tekton_style"))
    assert "accepted way to disclose" in t
    j = render.render_agents_md(policy_for("jaeger_style"))
    assert "Tick the AI-usage checkbox" in j


def test_agents_md_banned_and_empty():
    b = render.render_agents_md(policy_for("banned", repo="acme/banned"))
    assert "STOP: acme/banned does not accept AI-generated contributions" in b
    e = render.render_agents_md(Policy(repo="x/y"))
    assert "No AI-specific contribution rules were found" in e
    w = render.render_agents_md(policy_for("workflow"))
    assert "assigned" in w and "open or find an issue" in w
    d = render.render_agents_md(Policy(repo="x", disclosure_required=True, cla=True))
    assert "- Disclose AI assistance." in d and "CLA" in d


def test_conditional_cla_in_table_and_agents_md():
    from conftest import policy_from_text

    p = policy_from_text("## Legal\n\nA CLA is only required for larger changes.\n")
    assert "CLA only for some changes" in render.render(p, "table")
    agents = render.render_agents_md(p)
    assert "may need to sign the CLA" in agents and "must have signed the CLA" not in agents
    blanket = policy_from_text("## Legal\n\nAll contributors must sign the CLA.\n")
    assert "CLA yes" in render.render(blanket, "table")
    assert "must have signed the CLA" in render.render_agents_md(blanket)
